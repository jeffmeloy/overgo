//go:build ignore

// Generator for nfd_table.go — the committed canonical-decomposition table is
// the source of truth. Regenerating requires temporarily re-adding
// golang.org/x/text (this file's only dependency); the committed table is
// stdlib-only at runtime. The committed table is x/text's Unicode 15.0.0 data,
// which its norm package selects before Go 1.27.
//
// For each rune r in [0, 0x10FFFF] it computes norm.NFD.String(string(r)); if
// that differs from string(r), r has a canonical decomposition. Per-rune NFD is
// exactly the recursive canonical decomposition of r (canonical ordering of a
// single starting rune plus its marks is irrelevant here — see nfd.go). A
// surrogate converts to U+FFFD, which NFD leaves unchanged, so none is written.
// Hangul syllables are left out because appendNFD decomposes them by
// arithmetic. Each record is the rune followed by its decomposition and a
// space; no canonical decomposition contains a space.
//
//	go run gen_nfd_table.go   # writes nfd_table.go
package main

import (
	"fmt"
	"os"
	"slices"
	"strconv"
	"strings"
	"unicode"

	"golang.org/x/text/unicode/norm"
)

// hangulFirst and hangulLast bound the Hangul syllables, which decompose by
// the arithmetic of Unicode 16 section 3.12 rather than by table.
const hangulFirst, hangulLast = 0xAC00, 0xD7A3

// recordsPerLine wraps the packed string so no source line exceeds three
// hundred bytes.
const recordsPerLine = 8

func main() {
	var records []string
	for r := rune(0); r <= unicode.MaxRune; r++ {
		s := string(r)
		if decomposed := norm.NFD.String(s); decomposed != s && (r < hangulFirst || r > hangulLast) {
			records = append(records, s+decomposed+" ")
		}
	}
	var lines []string
	for chunk := range slices.Chunk(records, recordsPerLine) {
		lines = append(lines, strconv.QuoteToASCII(strings.Join(chunk, "")))
	}
	src := fmt.Sprintf(`// Code generated by gen_nfd_table.go; DO NOT EDIT.
// Regenerate with: go run gen_nfd_table.go (requires golang.org/x/text).
// Canonical (NFD, not NFKD) recursive per-rune decompositions. See nfd.go.

package tokenizer

// nfdPacked holds %d space-terminated records, each a rune followed by its
// fully-expanded recursive canonical decomposition. Hangul syllables are not
// recorded; appendNFD decomposes them by arithmetic.
const nfdPacked = "" +
	%s
`, len(records), strings.Join(lines, " +\n\t"))
	if err := os.WriteFile("nfd_table.go", []byte(src), 0o644); err != nil {
		panic(err)
	}

	fmt.Fprintf(os.Stderr, "generated nfd_table.go with %d records\n", len(records))
}
