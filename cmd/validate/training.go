// docs/TRAINING_COMPATIBILITY.md is published from the typed training
// specifications under docs/verification.
const (
	trainingMatrixPath           = "docs/TRAINING_COMPATIBILITY.md"
	trainingSpecificationPattern = "docs/verification/*training.json"
)

// verificationSpecification is one typed model-verification specification:
// a model's claims and the committed files that ground their evidence and
// datasets.
type verificationSpecification struct {
	Model         artifact.ID                 `json:"model"`
	Name          string                      `json:"name"`
	Supersedes    []artifact.ID               `json:"supersedes,omitempty"`
	EvidenceFiles []string                    `json:"evidence_files,omitempty"`
	DatasetFiles  []string                    `json:"dataset_files,omitempty"`
	Claims        []runrecord.CapabilityClaim `json:"claims"`
}

func generateTraining(root string) ([]byte, error) {
	records, err := loadTrainingVerifications(root)
	if err != nil {
		return nil, err
	}
	rows := runrecord.VerificationMatrix(records)
	claims := 0
	for _, row := range rows {
		for _, claim := range row.Capabilities {
			if trainingCapability(claim.Capability) {
				claims++
			}
		}
	}
	var output bytes.Buffer
	output.WriteString("# Training compatibility\n\n")
	output.WriteString("Generated from the typed training specifications under [`docs/verification`](verification). Do not edit this file directly.\n\n")
	fmt.Fprintf(&output, "%d model artifacts, %d strongest training claims.\n\n", len(rows), claims)
	output.WriteString("| Model | Capability | Tier | Span | Wall | Peak device | Commit |\n")
	output.WriteString("| --- | --- | --- | ---: | ---: | ---: | --- |\n")
	for _, row := range rows {
		for _, claim := range row.Capabilities {
			if !trainingCapability(claim.Capability) {
				continue
			}
			span := fmt.Sprintf("%d steps", claim.SpanSteps)
			if claim.SpanTokens != 0 {
				span += fmt.Sprintf(" / %d tokens", claim.SpanTokens)
			}
			wall := "-"
			if claim.WallNS != 0 {
				wall = time.Duration(claim.WallNS).Round(time.Millisecond).String()
			}
			peak := "-"
			if claim.PeakDeviceBytes != 0 {
				peak = fmt.Sprintf("%d B", claim.PeakDeviceBytes)
			}
			fmt.Fprintf(&output, "| `%s` | `%s` | `%s` | %s | %s | %s | `%s` |\n",
				escapeCell(row.Name), claim.Capability, claim.Tier, span, wall, peak, claim.Commit)
		}
	}
	output.WriteString("\nThe matrix reports evidence scope, not general model-family support. `real-artifact-smoke` establishes the named bounded run; it does not imply convergence, a complete training campaign, or production promotion.\n")
	return output.Bytes(), nil
}

// loadTrainingVerifications reads every training specification and holds
// each to its grounding: training claims with an observed span at a commit
// the repository holds, each backed by a committed evidence file.
func loadTrainingVerifications(root string) ([]runrecord.ModelVerification, error) {
	paths, err := filepath.Glob(filepath.Join(root, filepath.FromSlash(trainingSpecificationPattern)))
	if err != nil {
		return nil, err
	}
	if len(paths) == 0 {
		return nil, errors.New("training compatibility: no verification specifications")
	}
	slices.Sort(paths)
	records := make([]runrecord.ModelVerification, len(paths))
	for index, path := range paths {
		var specification verificationSpecification
		if err := jsonfile.Decode(path, &specification); err != nil {
			return nil, fmt.Errorf("training compatibility: %s: %w", filepath.ToSlash(path), err)
		}
		record, err := runrecord.NewModelVerificationCorrection(
			specification.Model, specification.Name, specification.Claims, specification.Supersedes,
		)
		if err != nil {
			return nil, fmt.Errorf("training compatibility: %s: %w", filepath.ToSlash(path), err)
		}
		if err := validateTrainingSpecification(root, specification, record); err != nil {
			return nil, fmt.Errorf("training compatibility: %s: %w", filepath.ToSlash(path), err)
		}
		records[index] = record
	}
	return records, nil
}

func validateTrainingSpecification(root string, specification verificationSpecification, record runrecord.ModelVerification) error {
	claimedEvidence := make(map[artifact.ID]bool)
	claimedDatasets := make(map[artifact.ID]bool)
	for _, claim := range record.Claims {
		if !trainingCapability(claim.Capability) {
			return fmt.Errorf("capability %q is not a training claim", claim.Capability)
		}
		if claim.SpanSteps == 0 && claim.SpanTokens == 0 {
			return fmt.Errorf("capability %q has no observed span", claim.Capability)
		}
		if _, err := gitauthority.Query(context.Background(), root, "cat-file", "-e", claim.Commit+"^{commit}"); err != nil {
			return fmt.Errorf("capability %q: commit %s is unavailable: %w", claim.Capability, claim.Commit, err)
		}
		claimedDatasets[claim.Dataset] = true
		for _, evidence := range claim.Evidence {
			claimedEvidence[evidence] = true
		}
	}
	localEvidence, err := referencedFileIDs(root, specification.EvidenceFiles, artifact.KindEvidence, claimedEvidence, false)
	if err != nil {
		return fmt.Errorf("evidence files: %w", err)
	}
	if len(localEvidence) == 0 {
		return errors.New("no local evidence file")
	}
	for _, claim := range record.Claims {
		if !slices.ContainsFunc(claim.Evidence, func(id artifact.ID) bool { return localEvidence[id] }) {
			return fmt.Errorf("capability %q has no locally grounded evidence", claim.Capability)
		}
	}
	if _, err := referencedFileIDs(root, specification.DatasetFiles, artifact.KindDatasetShard, claimedDatasets, true); err != nil {
		return fmt.Errorf("dataset files: %w", err)
	}
	return nil
}

func referencedFileIDs(root string, paths []string, kind artifact.Kind, claimed map[artifact.ID]bool, allowExternal bool) (map[artifact.ID]bool, error) {
	result := make(map[artifact.ID]bool, len(paths))
	seen := make(map[string]bool, len(paths))
	for _, path := range paths {
		if allowExternal && filepath.IsAbs(path) {
			continue
		}
		full, err := repositoryFile(root, path)
		if err != nil {
			return nil, err
		}
		if seen[full] {
			return nil, fmt.Errorf("duplicate path %s", path)
		}
		seen[full] = true
		data, err := os.ReadFile(full)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		id, err := artifact.IdentifyBytes(kind, data)
		if err != nil {
			return nil, err
		}
		if !claimed[id] {
			return nil, fmt.Errorf("%s identifies as unclaimed %s", path, id)
		}
		if result[id] {
			return nil, fmt.Errorf("duplicate identity %s", id)
		}
		result[id] = true
	}
	return result, nil
}

func repositoryFile(root, path string) (string, error) {
	if path == "" || filepath.IsAbs(path) {
		return "", fmt.Errorf("invalid repository path %q", path)
	}
	root, err := filepath.Abs(root)
	if err != nil {
		return "", err
	}
	full, err := filepath.Abs(filepath.Join(root, filepath.FromSlash(path)))
	if err != nil {
		return "", err
	}
	relative, err := filepath.Rel(root, full)
	if err != nil || relative == ".." || strings.HasPrefix(relative, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("path escapes repository: %q", path)
	}
	return full, nil
}

func trainingCapability(capability string) bool {
	return capability == "training" || strings.HasSuffix(capability, "-training")
}
