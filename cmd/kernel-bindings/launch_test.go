package main

import (
	"encoding/json"
	"go/scanner"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"testing"

	"overgo/internal/testcheck"
)

// generatedMark opens each file this command writes, which names every kernel and so launches none.
const generatedMark = "// Code generated by cmd/kernel-bindings"

// TestEveryKernelHasALaunch holds each kernel of the kernel manifest to a launch: a Go source of the module other than
// this command's own output names it, by its bindings constant or by its name in a string, as a launch does. A kernel
// nothing launches is compiled and loaded for nothing; it leaves its source.
func TestEveryKernelHasALaunch(t *testing.T) {
	t.Parallel()
	root := filepath.Join("..", "..")
	named := map[string]bool{}
	for _, tree := range []string{"cmd", "internal"} {
		testcheck.NoError(t, filepath.WalkDir(filepath.Join(root, tree), func(path string, entry fs.DirEntry, err error) error {
			if err != nil || entry.IsDir() || !strings.HasSuffix(path, ".go") {
				return err
			}
			source, err := os.ReadFile(path)
			if err != nil || strings.HasPrefix(string(source), generatedMark) {
				return err
			}
			var words scanner.Scanner
			words.Init(token.NewFileSet().AddFile(path, -1, len(source)), source, nil, 0)
			for _, kind, literal := words.Scan(); kind != token.EOF; _, kind, literal = words.Scan() {
				if kind == token.STRING {
					literal, _ = strconv.Unquote(literal)
				}
				named[literal] = true
			}
			return nil
		}))
	}
	var manifest kernelManifest
	testcheck.NoError(t, json.Unmarshal(testcheck.Must(os.ReadFile(filepath.Join(root, "kernels", "manifest.json")))(t), &manifest))
	for _, module := range manifest.Modules {
		for _, name := range module.Functions {
			if !named[name] && !named[kernelIdentifier(name)] {
				t.Errorf("%s: %s has no launch; remove it from its source", filepath.Base(module.Asset), name)
			}
		}
	}
}
