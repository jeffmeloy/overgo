// rewardSampler is the generator a reward session draws its answers by, from
// the weights as they stand. A model trained over a safetensors directory is
// sampled on the host from the model in training (modelSampler), one whole
// forward a token. A model trained over a GGUF is sampled by the inference
// runtime: the weights are written beside the run's output as the model the
// server opens (WriteTrainedModel) and opened as an inference candidate no
// store is told of, on the host or the device as the session trains. What is
// opened serves every group until a step moves the weights; then it is
// closed and what was written is removed, and the next group opens the
// weights after the step. So a real model's answers are generated by the
// runtime that serves it, a token at a time over its own cache, and training
// keeps no forward of its own to generate with.
type rewardSampler struct {
	session   denseSession
	tokens    trainableTokenizer
	runner    *inference.Runner
	directory string
}

// generator is the generator of the weights as they stand, which it opens
// when a step has moved them since they were last opened.
func (sampler *rewardSampler) generator() (evaluation.Generator, error) {
	session := sampler.session
	if !isGGUFModelInput(session.inputDirectory) {
		return modelSampler{model: session.model, tokens: sampler.tokens}, nil
	}
	if sampler.runner != nil {
		return sampler.runner, nil
	}
	// A session's weights are written to be opened; a reading opens the file its weights are.
	path := session.inputDirectory
	if session.model != nil {
		directory, err := os.MkdirTemp(filepath.Dir(session.request.OutputDirectory), "reward-weights-")
		if err != nil {
			return nil, err
		}
		sampler.directory = directory
		if err := WriteTrainedModel(session.ctx, session.request.Repository, path, directory, len(session.model.Weights), trainedGGUFTensors(session.model)); err != nil {
			return nil, err
		}
		path = filepath.Join(directory, trainingprogram.CheckpointModel)
	}
	candidate, err := modelintake.PrepareInferenceCandidate(session.ctx, session.request.Repository, path, modelintake.SessionOverride{}, recipe.ResidencyHybridNative)
	if err != nil {
		return nil, err
	}
	definition := candidate.Definition
	if session.request.Host {
		definition, err = modelrecipe.InferenceWithModelDefinition(candidate.Inventory.Manifest.ID, candidate.Resolved.Profile.ID, candidate.Resolved.Document.ID,
			recipe.PlacementHost, modelrecipe.DecodeSessionRequest, recipe.ResidencyHostReference)
		if err != nil {
			return nil, err
		}
	}
	loaded, err := modelrecipe.ResolveCandidateGGUF(path, definition, candidate.Resolved)
	if err != nil {
		return nil, err
	}
	if sampler.runner, err = inference.OpenWithProgram(session.ctx, &loaded, inference.OpenOptions{}); err != nil {
		return nil, errors.Join(err, loaded.Close())
	}
	return sampler.runner, nil
}

// draw is the first draws of one prompt under a reward session's protocol,
// from the weights named. The prompt is asked as the protocol's template asks
// it: as it is written under rewardPlain, and otherwise as a user's turn with
// the reply invited, rendered by the session's renderer or, where it has
// none, by the runtime the weights are opened in. The group of its draws is
// named from the code, the weights, the base's tokenizer, the template, the
// prompt's ids, the vocabulary's ending ids, the seed and the output limit,
// which is the least of the protocol's, the prompt's own, and what the
// protocol's window and the model's context leave after the prompt. The draws
// the store holds of the group are read back and the rest sampled and kept
// (evaluation.SampleGroup).
func (sampler *rewardSampler) draw(rewards RewardSampling, name, prompt string, limit int, base, weights artifact.ID) (evaluation.SampledGroup, []evaluation.SampledAnswer, error) {
	session := sampler.session
	generator, err := sampler.generator()
	if err != nil {
		return evaluation.SampledGroup{}, nil, err
	}
	switch plain := rewards.Protocol.Template == rewardPlain; {
	case rewards.Render != nil:
		prompt, err = rewards.Render([]dataset.ChatMessage{{Role: string(inference.ChatRoleUser), Content: prompt}}, true)
	case !plain && sampler.runner != nil:
		prompt, err = sampler.runner.FormatChatWithOptions([]inference.ChatMessage{{Role: inference.ChatRoleUser, Content: prompt}}, inference.ChatFormatOptions{AddGenerationPrompt: true})
	case !plain:
		err = fmt.Errorf("template %q has no renderer: a model that is not a GGUF is given one", rewards.Protocol.Template)
	}
	var encoded []int
	if err == nil {
		encoded, err = sampler.tokens.encode(prompt)
	}
	if err != nil {
		return evaluation.SampledGroup{}, nil, fmt.Errorf("training workflow: prompt %q: %w", name, err)
	}
	group := evaluation.SampledGroup{
		Group: name, Code: rewards.Code, Weights: weights, Tokenizer: base, Template: rewards.Protocol.Template, Temperature: 1, Seed: rewards.Seed,
		MaxTokens: min(int(rewards.Protocol.MaxTokens), limit, int(rewards.Protocol.Window)-len(encoded)),
	}
	if session.model != nil {
		group.MaxTokens = min(group.MaxTokens, session.model.Dims.ContextLength-len(encoded))
	}
	for _, id := range encoded {
		group.Prompt = append(group.Prompt, tokenizer.TokenID(id))
	}
	for _, id := range sampler.tokens.ends {
		group.Ends = append(group.Ends, tokenizer.TokenID(id))
	}
	answers, err := evaluation.SampleGroup(session.ctx, session.request.Observations, generator, group, rewards.Draws)
	return group, answers, err
}

// standing is the logarithm of the probability the weights as they stand give
// each answer of a group after its prompt, over the answer's own ids: scored
// by the runtime the weights are opened in, which opens them when a step has
// moved them, or by the model in training where that is what samples.
func (sampler *rewardSampler) standing(prompt []tokenizer.TokenID, answers []evaluation.SampledAnswer, rollouts []trainingdata.Rollout) ([]float64, error) {
	if _, err := sampler.generator(); err != nil {
		return nil, err
	}
	standing := make([]float64, len(rollouts))
	if sampler.runner == nil {
		for index, rollout := range rollouts {
			score, err := sampler.session.model.SequenceLogProb(rollout.Sequence)
			if err != nil {
				return nil, err
			}
			standing[index] = score.LogProbability
		}
		return standing, nil
	}
	completions := make([][]tokenizer.TokenID, len(answers))
	for index, answer := range answers {
		completions[index] = answer.Completion
	}
	scores, err := sampler.runner.ScoreContinuationTokens(sampler.session.ctx, prompt, completions)
	if err != nil {
		return nil, err
	}
	for index, score := range scores {
		standing[index] = score.LogProbability
	}
	return standing, nil
}

// release closes what is open of the weights and removes what was written of
// them: after a step has moved them, and when the session ends.
func (sampler *rewardSampler) release() error {
	var err error
	if sampler.runner != nil {
		err = sampler.runner.Close()
	}
	if sampler.directory != "" {
		err = errors.Join(err, os.RemoveAll(sampler.directory))
	}
	sampler.runner, sampler.directory = nil, ""
	return err
}
